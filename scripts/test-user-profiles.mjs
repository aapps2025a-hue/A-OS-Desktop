import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const data = new Map();
const storage = {
  get length() { return data.size; }, key(i) { return [...data.keys()][i]; },
  getItem(k) { return data.get(k) ?? null; },
  setItem(k, v) { data.set(k, String(v)); }, removeItem(k) { data.delete(k); }
};
const context = { window: {}, localStorage: storage };
vm.runInNewContext(readFileSync(new URL('../public/aos-user-profiles.js', import.meta.url), 'utf8'), context);
const api = context.window.AOS_USER_PROFILES;
api.configure(['aos-wallpaper', 'aos-shelf-position', 'aos-dark', 'aos-files', 'aos-device', 'aos-configured', 'aos-profiles']);
storage.setItem('aos-profile', 'Alice');
storage.setItem('aos-device', 'Shared PC');
storage.setItem('aos-profiles', '["Alice","Bob"]');
storage.setItem(api.passwordKey('Alice'), 'alice-secret');
storage.setItem(api.passwordKey('Bob'), 'bob-secret');
storage.setItem('aos-password', 'alice-secret');
storage.setItem('aos-wallpaper', 'Porto.png');
storage.setItem('aos-shelf-position', 'left');
storage.setItem('aos-dark', 'true');
storage.setItem('aos-window-size-Files', 'alice-size');
storage.setItem('aos-aapplications-session', 'alice-session');
api.activate({name: 'Bob'}, true);
assert.equal(storage.getItem('aos-password'), 'bob-secret');
assert.equal(storage.getItem('aos-configured'), 'true');
assert.equal(storage.getItem('aos-wallpaper'), null);
assert.equal(storage.getItem('aos-aapplications-session'), null);
assert.equal(storage.getItem('aos-window-size-Files'), null);
storage.setItem('aos-wallpaper', 'Faro.jpg');
storage.setItem('aos-shelf-position', 'right');
storage.setItem('aos-dark', 'false');
storage.setItem('aos-files', '["bob-file"]');
api.activate({name: 'Alice'});
assert.equal(storage.getItem('aos-password'), 'alice-secret');
assert.equal(storage.getItem('aos-wallpaper'), 'Porto.png');
assert.equal(storage.getItem('aos-shelf-position'), 'left');
assert.equal(storage.getItem('aos-dark'), 'true');
assert.equal(storage.getItem('aos-files'), null);
assert.equal(storage.getItem('aos-window-size-Files'), 'alice-size');
assert.equal(storage.getItem('aos-aapplications-session'), 'alice-session');
storage.setItem(api.passwordKey('Alice'), 'new-alice-secret');
api.activate({name: 'Bob'});
assert.equal(storage.getItem('aos-password'), 'bob-secret');
assert.equal(storage.getItem('aos-wallpaper'), 'Faro.jpg');
assert.equal(storage.getItem('aos-shelf-position'), 'right');
assert.equal(storage.getItem('aos-files'), '["bob-file"]');
api.activate({name: 'Alice'});
assert.equal(storage.getItem('aos-password'), 'new-alice-secret');
assert.equal(storage.getItem('aos-device'), 'Shared PC');
assert.equal(storage.getItem('aos-profiles'), '["Alice","Bob"]');
storage.setItem('aos-profile-workspace-Corrupt', '{');
assert.throws(() => api.activate({name: 'Corrupt'}));
assert.equal(storage.getItem('aos-profile'), 'Alice');
assert.equal(storage.getItem('aos-wallpaper'), 'Porto.png');
const realSet = storage.setItem;
storage.setItem = (k, v) => { if (k === 'aos-profile-workspace-Alice') throw new Error('Quota'); realSet(k,v); };
storage.setItem('aos-wallpaper', 'custom.png');
assert.throws(() => api.activate({name: 'Bob'}), /Quota/);
assert.equal(storage.getItem('aos-profile'), 'Alice');
assert.equal(storage.getItem('aos-wallpaper'), 'custom.png');
console.log('PASS: profile passwords, preferences, files, sessions, new-user setup and failure safety');
